#!/usr/bin/env node
// Upload sheets for one informational short: youtube.md, tiktok.md and instagram.md, built from
// the episode's publish.json, research ledgers (traced and cited with shorts-research), storyboard.json
// and the channel's defaults, so every platform gets the same checked text.
//   node upload.mjs <episode-dir> --out <upload-dir> [--channel <channel.json>] [--video <mp4>]
//                   [--thumbnail <png>] [--force]
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { trace, cite, screenItems } from '../../shorts-research/scripts/facts.mjs';

export const CHANNEL_SCHEMA = 'shorts-channel/1';
export const MARK = '<!-- generated by shorts-publish upload.mjs: edit publish.json or the channel file, then run it again -->';
// Platform limits as checked on 2026-10-20 (see references/platforms.md).
export const LIMITS = {
  youtube: { title: 100, description: 5000, hashtags: 15 },
  tiktok: { caption: 4000, hashtags: 5 },
  instagram: { caption: 2200, hashtags: 5, visible: 125 },
  maxSeconds: 180,
  rewardsSeconds: 60,
};
export const DEFAULT_CHANNEL = {
  schema: CHANNEL_SCHEMA,
  name: '',
  language: '한국어',
  category: '교육',
  correction: '틀린 내용이 있으면 댓글로 알려 주세요. 확인한 뒤 고정 댓글로 바로잡겠습니다.',
  first_comment: '',
  youtube_only_hashtags: ['#쇼츠', '#shorts'],
};

// Rows of the number table: same claims this close together are one moment on screen.
export const MERGE_SECONDS = 1.5;
// Evidence entries shown per row; the rest are counted.
export const MAX_BASIS = 3;

const str = (v) => typeof v === 'string' && v.trim() !== '';
const isObj = (v) => v !== null && typeof v === 'object' && !Array.isArray(v);

/**
 * A string or a list of strings as a list of non-empty strings.
 * @param {unknown} v
 * @returns {string[]}
 */
export function lines(v) {
  if (Array.isArray(v)) return v.filter(str);
  return str(v) ? [v] : [];
}

/**
 * Seconds as m:ss.
 * @param {number} t
 * @returns {string}
 */
export function mmss(t) {
  const s = Math.floor(t);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

/**
 * Hashtags for a platform: drop the YouTube-only ones (case-insensitive), keep order, no duplicates.
 * @param {string[]} tags
 * @param {string[]} youtubeOnly
 * @param {number} max
 * @returns {string[]}
 */
export function pickHashtags(tags, youtubeOnly, max) {
  const skip = new Set(youtubeOnly.map((t) => t.toLowerCase()));
  const out = [];
  for (const t of tags) if (!skip.has(t.toLowerCase()) && !out.includes(t)) out.push(t);
  return out.slice(0, max);
}

/**
 * On-screen numbers with their time and evidence: storyboard captions and overlays that hold a
 * digit and list claims, one row per distinct text. A caption and an overlay that show the same
 * claims within MERGE_SECONDS share one row ("점은 36개 / 36개").
 * @param {any} storyboard
 * @param {any} facts
 * @param {any} sources
 * @returns {{at: number|null, text: string, claims: string[], basis: string[]}[]}
 */
export function numberRows(storyboard, facts, sources) {
  const claims = new Map((facts.claims || []).map((c) => [c.id, c]));
  const pubs = new Map((sources.sources || []).map((s) => [s.id, s.publisher]));
  const rows = [];
  for (const it of screenItems(storyboard, null)) {
    if (!/\d/.test(it.text) || !Array.isArray(it.claims) || !it.claims.length) continue;
    if (rows.some((r) => r.text === it.text)) continue;
    const m = / @([\d.]+)s$/.exec(it.where);
    const basis = [];
    for (const id of it.claims) {
      for (const r of claims.get(id)?.sources || []) {
        const b = [pubs.get(r.id) || r.id, r.locator].filter(str).join(' ');
        if (!basis.includes(b)) basis.push(b);
      }
    }
    rows.push({ at: m ? Number(m[1]) : null, text: it.text, claims: it.claims, basis });
  }
  rows.sort((a, b) => (a.at ?? Infinity) - (b.at ?? Infinity));
  const merged = [];
  for (const r of rows) {
    const prev = merged[merged.length - 1];
    if (prev && r.at !== null && prev.at !== null && r.at - prev.at < MERGE_SECONDS && prev.claims.join() === r.claims.join()) prev.text += ` / ${r.text}`;
    else merged.push(r);
  }
  return merged;
}

/**
 * On-screen numbers that facts.mjs trace cannot see, because it reads only an overlay's text and label:
 * a timer's count, a number's sub line, a card title, compare items, stage rows, buckle labels.
 * A person compares these with the ledger by hand.
 * @param {any} storyboard
 * @returns {{at: number|null, kind: string, texts: string[], claims: string[]}[]}
 */
export function handCheckRows(storyboard) {
  const out = [];
  for (const o of Array.isArray(storyboard.overlays) ? storyboard.overlays : []) {
    if (!isObj(o)) continue;
    const texts = [];
    if (o.kind === 'timer' && o.to !== undefined) texts.push(`${o.to}${o.unit ?? '초'}`);
    texts.push(...[o.sub, o.title, o.skin, o.flesh].filter(str));
    for (const it of Array.isArray(o.items) ? o.items : []) if (isObj(it)) texts.push(...[it.label, it.text].filter(str));
    for (const r of Array.isArray(o.rows) ? o.rows : []) if (isObj(r)) texts.push([r.name, r.text].filter(str).join(' '));
    const shown = texts.filter((s) => /\d/.test(s));
    if (shown.length) out.push({ at: typeof o.start === 'number' ? o.start : null, kind: o.kind, texts: shown, claims: lines(o.claims) });
  }
  return out;
}

/**
 * Build the three sheets. Nothing is written here.
 * @param {{id: string, publish: any, facts: any, sources: any, storyboard: any, thumbnail?: any,
 *   channel?: any, video: string, cover: string, videoExists: boolean, coverExists: boolean,
 *   urlsFile?: string|null}} input
 * @returns {{files: Record<string, string>, errors: string[], warnings: string[]}}
 */
export function build(input) {
  const { id, publish, facts, sources, storyboard } = input;
  const ch = { ...DEFAULT_CHANNEL, ...(input.channel || {}) };
  const errors = [];
  const warnings = [];
  if (ch.schema !== CHANNEL_SCHEMA) errors.push(`channel: schema must be "${CHANNEL_SCHEMA}"`);
  const t = trace(facts, storyboard, publish, input.thumbnail || null);
  errors.push(...t.errors);
  warnings.push(...t.warnings);

  const titles = lines(publish.title);
  const summary = lines(publish.description);
  const tags = lines(publish.hashtags);
  if (!titles.length) errors.push('publish: title is missing');
  if (!summary.length) errors.push('publish: description is missing');
  if (!str(publish.disclosure)) warnings.push('publish: no disclosure line (AI picture and voice notice)');
  const duration = typeof storyboard.duration === 'number' ? storyboard.duration : null;
  if (duration === null) warnings.push('storyboard: no duration; check the video length by hand');
  else if (duration > LIMITS.maxSeconds) errors.push(`video is ${duration} s; Shorts and Reels allow ${LIMITS.maxSeconds} s`);
  if (!input.videoExists) warnings.push(`video not found: ${input.video}`);
  const cover = isObj(publish.cover) && typeof publish.cover.at === 'number' ? publish.cover : null;
  if (!cover) warnings.push('publish: no cover {at, note}; pick the cover frame by hand');

  const title = titles[0] || '';
  const ytTags = pickHashtags(tags, [], Infinity);
  const shortTags = (max) => pickHashtags(tags, lines(ch.youtube_only_hashtags), max);
  const srcList = cite(sources, facts, t.used, { urls: false });
  const tail = [lines(publish.disclosure).join(''), ch.correction].filter(str).join('\n');
  const join = (...parts) => parts.filter(str).join('\n\n');
  const ytDesc = join(summary.join('\n'), srcList, tail, ytTags.join(' '));
  const ttCap = join(title, summary.join('\n'), srcList, tail, shortTags(LIMITS.tiktok.hashtags).join(' '));
  const igCap = join(title, summary.join('\n'), srcList, tail, shortTags(LIMITS.instagram.hashtags).join(' '));
  const len = (s) => [...s].length;
  if (len(title) > LIMITS.youtube.title) errors.push(`youtube: title is ${len(title)} characters (max ${LIMITS.youtube.title})`);
  if (len(ytDesc) > LIMITS.youtube.description) errors.push(`youtube: description is ${len(ytDesc)} characters (max ${LIMITS.youtube.description})`);
  // YouTube refuses "<" and ">" in titles, descriptions and tags (the upload form reports invalid characters).
  for (const [what, text] of [['title', titles.join('\n')], ['description', ytDesc], ['tags', lines(publish.tags).join(', ')]]) {
    if (/[<>]/.test(text)) errors.push(`youtube: ${what} contains "<" or ">", which YouTube does not allow; write "→" or words instead (publish.json, or a source title in research/sources.json)`);
  }
  if (ytTags.length > LIMITS.youtube.hashtags) errors.push(`youtube: ${ytTags.length} hashtags; over ${LIMITS.youtube.hashtags} YouTube ignores them all`);
  if (len(ttCap) > LIMITS.tiktok.caption) errors.push(`tiktok: caption is ${len(ttCap)} characters (max ${LIMITS.tiktok.caption})`);
  if (len(igCap) > LIMITS.instagram.caption) errors.push(`instagram: caption is ${len(igCap)} characters (max ${LIMITS.instagram.caption})`);
  if (len(title) > LIMITS.instagram.visible) warnings.push(`instagram: the first line is over ${LIMITS.instagram.visible} characters and is cut before "more"`);

  const name = str(publish.name) ? publish.name : id;
  const chName = str(ch.name) ? ` (${ch.name})` : '';
  const secs = duration === null ? '길이 미확인' : `${duration.toFixed(1)}초`;
  const head = (platform) => [
    MARK,
    `# ${platform} 업로드 정보: ${name}${chName}`,
    '',
    `- 영상: \`${input.video}\` (${secs}, 1080x1920, 세로). 다른 플랫폼에서 내려받은 파일이 아니라 이 원본을 올린다.`,
    `- 바탕 자료: \`publish.json\`, 사실 장부(\`research/\`), \`storyboard.json\`. 이 파일을 고치지 말고 바탕 자료를 고친 뒤 다시 만든다.`,
    `- 출처의 웹 주소는 넣지 않았다(설명란·캡션 링크는 눌리지 않는다).${input.urlsFile ? ` 주소는 \`${input.urlsFile}\`에 있다.` : ''}`,
  ];
  const block = (text) => ['```text', text, '```'];
  const table = (rows) => ['| 항목 | 값 |', '|---|---|', ...rows.map(([k, v]) => `| ${k} | ${v} |`)];
  const frame = cover ? `**${mmss(cover.at)} 프레임**${str(cover.note) ? `(${cover.note})` : ''}` : '제목의 주제가 가장 잘 보이는 프레임';
  const coverFile = input.coverExists ? `\`${input.cover}\`` : null;
  const firstComment = str(publish.first_comment) ? publish.first_comment : ch.first_comment;
  const comment = (label) => (str(firstComment) ? ['', `## ${label}`, '', ...block(firstComment)] : []);

  const reviewed = isObj(facts.review) && str(facts.review.by) && str(facts.review.on);
  const singles = t.used.filter((cid) => facts.claims.find((c) => c.id === cid)?.status === 'single-source');
  const hand = handCheckRows(storyboard);
  const checks = (platform) => [
    '',
    '## 올리기 전 확인',
    '',
    reviewed ? `- [x] 사실 장부 검토: ${facts.review.by}, ${facts.review.on}` : '- [ ] **사실 장부 검토 기록이 없다.** 사람이 `research/facts.json`을 읽고 `review {by, on}`을 남겨야 올릴 수 있다.',
    ...singles.map((cid) => `- [ ] \`${cid}\`는 출처가 하나뿐이다. 문장에서 범위를 좁혀 말했는지 확인한다.`),
    '- [x] 화면·제목·설명·해시태그·썸네일의 숫자 추적: 오류 0',
    ...(hand.length ? [`- [ ] 화면 숫자 ${hand.length}곳은 추적 검사가 읽지 못한다(카드 줄, 막대 문구, 타이머 숫자 등). ${platform === 'youtube' ? '아래 "직접 대조할 화면 숫자" 표' : 'youtube.md의 "직접 대조할 화면 숫자" 표'}를 \`research/facts.json\`과 대조한다.`] : []),
    input.videoExists ? `- [x] 영상 파일 있음: \`${input.video}\`` : `- [ ] **영상 파일이 없다:** \`${input.video}\``,
    ...(platform === 'tiktok' && duration !== null
      ? [duration > LIMITS.rewardsSeconds ? `- [x] 길이 ${secs}: 틱톡 수익화(1분 초과) 길이 조건을 채운다` : `- [ ] 길이 ${secs}: 1분 이하라 틱톡 수익화(Creator Rewards) 대상이 아니다`]
      : []),
  ];

  const rows = numberRows(storyboard, facts, sources);
  const youtube = [
    ...head('유튜브'),
    '', '## 1. 제목', '', ...block(title),
    ...(titles.length > 1 ? ['', `다른 안: ${titles.slice(1).map((x) => `\`${x}\``).join(', ')}`] : []),
    '', '## 2. 설명', '', '아래 블록을 통째로 붙여 넣는다. 해시태그 중 앞의 3개는 제목 위에 보인다.', '', ...block(ytDesc),
    '', '## 3. 업로드 설정', '',
    ...table([
      ['공개 범위', '처음엔 **비공개**로 올리고, 휴대폰에서 한 번 본 뒤 공개 또는 예약'],
      ['썸네일', `쇼츠 맞춤 썸네일은 파트너 프로그램 채널만 올릴 수 있다. 앱 업로드 화면에서 ${frame}을 고른다.${coverFile ? ` 맞춤 썸네일이 열리면 ${coverFile}를 쓴다` : ''}`],
      ['시청자층', publish.made_for_kids ? '아동용' : '아동용 아님'],
      ['변경되거나 합성된 콘텐츠', publish.altered_content ? '예' : '아니요 (실제 인물·장소·사건처럼 보이게 만든 장면이 없고, 내레이터도 가상)'],
      ['카테고리', ch.category],
      ['언어 / 자막 언어', `${ch.language} / ${ch.language} (자막이 영상에 박혀 있으므로 자동 자막은 꺼도 된다)`],
      ['댓글', '허용'],
      ['태그', lines(publish.tags).join(', ') || '(없음)'],
      ['재생목록', str(publish.playlist) ? publish.playlist : '(없음)'],
    ]),
    ...comment('4. 첫 고정 댓글 (선택)'),
    ...checks('youtube'),
    ...(rows.length
      ? ['', '화면에 나오는 숫자와 근거:', '', '| 화면 | 시각 | 근거 |', '|---|---|---|',
        ...rows.map((r) => `| ${r.text} | ${r.at === null ? '-' : mmss(r.at)} | ${r.basis.slice(0, MAX_BASIS).join('; ') || r.claims.join(', ')}${r.basis.length > MAX_BASIS ? ` 외 ${r.basis.length - MAX_BASIS}곳` : ''} |`)]
      : []),
    ...(hand.length
      ? ['', '직접 대조할 화면 숫자 (추적 검사가 읽지 못함):', '', '| 화면 | 시각 | 종류 | 주장 |', '|---|---|---|---|',
        ...hand.map((h) => `| ${h.texts.join(' / ')} | ${h.at === null ? '-' : mmss(h.at)} | ${h.kind} | ${h.claims.join(', ') || '**없음**'} |`)]
      : []),
  ];
  const tiktok = [
    ...head('틱톡'),
    '', '## 1. 캡션', '', '아래 블록을 통째로 붙여 넣는다. 첫 줄이 훅이다(접힌 상태에서는 앞부분만 보인다). 해시태그는 5개까지만 넣었다.', '', ...block(ttCap),
    '', '## 2. 업로드 설정', '',
    ...table([
      ['커버', coverFile ? `${coverFile}를 올린다. 이미지를 올릴 수 없으면 ${frame}을 고른다` : `${frame}을 고른다`],
      ['AI 생성 콘텐츠', '**켠다** (더 보기 > AI 생성 콘텐츠). 그림 파일의 C2PA 정보로 틱톡이 자동 표시하기도 한다'],
      ['사운드', '영상 원래 소리만 쓴다. 틱톡 음원을 더하지 않는다(내레이션과 겹친다)'],
      ['시청 가능 대상', '처음엔 **나만 보기**로 올려 휴대폰에서 본 뒤 모든 사람으로 바꾸거나 예약 게시'],
      ['댓글 / 듀엣 / 이어 찍기', '허용'],
      ['위치', '비워 둔다'],
      ['콘텐츠 공개(브랜드 콘텐츠)', '끈다 (광고가 아니다)'],
    ]),
    ...comment('3. 첫 댓글 (올린 직후, 선택)'),
    ...checks('tiktok'),
  ];
  const instagram = [
    ...head('인스타그램 릴스'),
    '', '## 1. 캡션', '', `아래 블록을 통째로 붙여 넣는다. 첫 줄 ${LIMITS.instagram.visible}자 정도만 "더 보기" 앞에 보인다. 해시태그는 인스타그램 제한에 맞춰 5개까지만 넣었다.`, '', ...block(igCap),
    '', '## 2. 업로드 설정', '',
    ...table([
      ['커버', `${coverFile ? `커버 수정 > 카메라 롤에서 ${coverFile}를 고른다. 없으면 ` : ''}${frame}을 고른다. 프로필 격자에서는 가운데 3:4만 보인다`],
      ['AI 정보 라벨', '**켠다** (고급 설정 > AI 라벨 추가). 메타는 C2PA 정보를 읽어 자동으로 붙이기도 한다'],
      ['오디오', '영상 원래 소리만 쓴다'],
      ['피드에도 공유', '켠다'],
      ['위치 / 사람 태그', '비워 둔다'],
      ['브랜디드 콘텐츠 / 유료 파트너십', '끈다 (광고가 아니다)'],
      ['댓글', '허용'],
    ]),
    ...comment('3. 첫 댓글 (선택)'),
    ...checks('instagram'),
  ];
  const files = { 'youtube.md': youtube, 'tiktok.md': tiktok, 'instagram.md': instagram };
  return { files: Object.fromEntries(Object.entries(files).map(([k, v]) => [k, `${v.join('\n')}\n`])), errors, warnings };
}

export const USAGE = `usage: upload.mjs <episode-dir> --out <upload-dir> [--channel <channel.json>]
                  [--video <mp4>] [--thumbnail <png>] [--force]
  writes youtube.md, tiktok.md and instagram.md into --out.
  --video and --thumbnail default to <id>.mp4 and <id>-thumbnail.png next to --out.
  --force replaces sheets that were not made by this script.`;

/**
 * Parse command-line options.
 * @param {string[]} argv
 * @returns {{dir?: string, opts: Record<string, string|boolean>, bad?: string}}
 */
export function parseArgs(argv) {
  const opts = {};
  const pos = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--force') opts.force = true;
    else if (a.startsWith('--')) {
      const v = argv[i + 1];
      if (v === undefined || v.startsWith('--')) return { opts, bad: `${a} needs a value` };
      opts[a.slice(2)] = v;
      i++;
    } else pos.push(a);
  }
  return { dir: pos[0], opts };
}

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const rel = (p) => path.relative(process.cwd(), p);

/**
 * Command-line entry point.
 * @param {string[]} argv
 * @param {{out: (s: string) => void, err: (s: string) => void}} io
 * @returns {number} exit code (0 written, 1 findings or bad files, 2 usage)
 */
export function main(argv, io) {
  const { dir, opts, bad } = parseArgs(argv);
  if (bad || !dir || typeof opts.out !== 'string') {
    io.err(bad ? `error: ${bad}\n${USAGE}` : USAGE);
    return 2;
  }
  const id = path.basename(path.resolve(dir));
  const outDir = path.resolve(opts.out);
  const video = path.resolve(opts.video || path.join(outDir, '..', `${id}.mp4`));
  const cover = path.resolve(opts.thumbnail || path.join(outDir, '..', `${id}-thumbnail.png`));
  let input;
  try {
    const opt = (f) => (fs.existsSync(f) ? readJson(f) : null);
    const urls = path.join(dir, 'sources.txt');
    input = {
      id,
      publish: readJson(path.join(dir, 'publish.json')),
      facts: readJson(path.join(dir, 'research', 'facts.json')),
      sources: readJson(path.join(dir, 'research', 'sources.json')),
      storyboard: readJson(path.join(dir, 'storyboard.json')),
      thumbnail: opt(path.join(dir, 'thumbnail.json')),
      channel: opts.channel ? readJson(opts.channel) : null,
      video: rel(video),
      cover: rel(cover),
      videoExists: fs.existsSync(video),
      coverExists: fs.existsSync(cover),
      urlsFile: fs.existsSync(urls) ? rel(urls) : null,
    };
  } catch (e) {
    io.err(`error: ${e.message}`);
    return 1;
  }
  const { files, errors, warnings } = build(input);
  for (const name of Object.keys(files)) {
    const f = path.join(outDir, name);
    if (!opts.force && fs.existsSync(f) && !fs.readFileSync(f, 'utf8').includes(MARK)) {
      errors.push(`${rel(f)} was written by hand; move it away or pass --force to replace it`);
    }
  }
  errors.forEach((e) => io.err(`error: ${e}`));
  warnings.forEach((w) => io.err(`warning: ${w}`));
  if (errors.length) {
    io.out(`${errors.length} error(s), ${warnings.length} warning(s); nothing written.`);
    return 1;
  }
  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(outDir, name), text);
  io.out(`Wrote ${Object.keys(files).map((n) => rel(path.join(outDir, n))).join(', ')} (${warnings.length} warning(s)).`);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2), { out: (s) => console.log(s), err: (s) => console.error(s) });
}
